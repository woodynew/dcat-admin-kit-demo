import { test, expect } from '@playwright/test';

test('访客可以切换语言，普通页面与 iframe 跟随并保留选择', async ({ page }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/');
    await page.locator('form[action$="/demo/enter"] button[type="submit"]').click();
    await expect(page).toHaveURL(/\/admin\/demo\/overview$/);
    const switcher = page.locator('.dcat-kit-locale');
    await expect(switcher).toBeVisible();
    await expect(switcher).toHaveValue('zh_CN');
    await switcher.selectOption('en');
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await expect(switcher).toHaveValue('en');
    await page.goto('/admin/demo/columns');
    await expect(switcher).toHaveValue('en');
    await expect(page.locator('.user-name')).toHaveText('Demo visitor');
    await expect(page.locator('.main-menu').getByText('Column displayers', {exact: true})).toBeVisible();
    await expect(page.getByTestId('nav-columns')).toHaveText('Column displayers');
    await expect(page.locator('.demo-page-intro h2')).toHaveText('Column displayers');
    await expect(page.locator('.demo-page-intro p').last()).toContainText('Open QR codes');
    await expect(page.getByTestId('live-example').locator('thead')).toContainText('Compact information');
    await expect(page.getByTestId('live-example')).toContainText('Title:');
    const control = await switcher.evaluate(element => {
        const style = getComputedStyle(element);
        return {height: element.clientHeight, padding: parseFloat(style.paddingTop) + parseFloat(style.paddingBottom), font: parseFloat(style.fontSize), width: element.clientWidth};
    });
    expect(control.height - control.padding).toBeGreaterThanOrEqual(control.font * 1.2);
    expect(control.width).toBeGreaterThanOrEqual(118);
    const logoFits = await page.locator('.logo-lg').evaluate(element => element.getBoundingClientRect().right <= element.closest('.main-sidebar').getBoundingClientRect().right);
    expect(logoFits).toBe(true);
    await page.screenshot({path: '/tmp/dcat-demo-columns-en.png'});
    await page.getByTestId('nav-actions').click();
    await expect(page.locator('.demo-page-intro h2')).toHaveText('Actions and tools');
    await expect(page.getByTestId('live-example')).toContainText('Post a demo notice');
    await page.getByTestId('nav-records').click();
    await expect(page.locator('.demo-page-intro h2')).toHaveText('Shared records');
    await page.getByTestId('nav-widgets').click();
    await expect(page.locator('.demo-page-intro h2')).toHaveText('Widgets and summaries');
    await page.getByTestId('nav-features').click();
    await expect(page.getByTestId('feature-grid_defaults').locator('h3')).toHaveText('Grid defaults');
    await page.goto('/admin/demo/tabs');
    await expect(page.locator('.tab-close-all')).toHaveText('Close all tabs');
    await expect(page.locator('#iframe-tab .nav-link')).toHaveCount(1);
    await switcher.selectOption('zh_TW');
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-TW');
    await expect(page.locator('.tab-close-all')).toHaveText('關閉所有分頁');
    await expect(page.getByTestId('tabs-menu-records')).toHaveText('共享記錄');
    await switcher.selectOption('zh_CN');
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
    await expect(page.locator('.tab-close-all')).toHaveText('关闭所有标签页');
    expect(errors).toEqual([]);
});
